import sys

# Зчитуємо аргументи з командного рядка
# sys.argv[0] — це назва файлу, самі дані починаються з індексу 1
a = float(sys.argv[1])  # Перший катет
b = float(sys.argv[2])  # Другий катет
h = float(sys.argv[3])  # Висота призми

# Формула об'єму: площа трикутника (0.5 * a * b) помножена на висоту (h)
volume = 0.5 * a * b * h

print("Об'єм призми:", volume)
