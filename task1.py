# Запит чотиризначного числа у користувача
number_str = input("Введіть чотиризначне число: ")

# Витягуємо дві середні цифри за їхніми індексами у рядку
# (у 4-значному числі індекси: 0, 1, 2, 3. Середні — це 1 та 2)
digit2 = int(number_str[1])
digit3 = int(number_str[2])

# Рахуємо суму та добуток
digit_sum = digit2 + digit3
digit_prod = digit2 * digit3

# Виведення результату в консоль
print("Сума середніх цифр:", digit_sum)
print("Добуток середніх цифр:", digit_prod)
